import Foundation
import UniformTypeIdentifiers

/// Decides what to do with the pasteboard from its type identifiers alone. Reading types does not
/// trigger the macOS pasteboard privacy alert; reading data does.
public enum ClipboardRules {
    /// Added to everything Squish writes, so it never processes its own output.
    public static let markerType = "\(AppIdentity.bundleID).optimized"

    /// nspasteboard.org conventions used by password managers and clipboard tools.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Preferred order when an app offers several representations.
    public static let imageTypes: [UTType] = [.png, .jpeg, .heic, .gif, .webP, .tiff]

    public enum Action: Equatable, Sendable {
        case ignore
        case files
        case image(UTType)
    }

    public static func action(for types: [String], kinds: Set<FileKind>) -> Action {
        if types.contains(markerType) || types.contains(where: ignoredTypes.contains) { return .ignore }
        // Finder copies carry the file icon as TIFF too; the files are what the user copied.
        if types.contains(UTType.fileURL.identifier) { return kinds.isEmpty ? .ignore : .files }
        guard kinds.contains(.image) else { return .ignore }
        for type in imageTypes where types.contains(type.identifier) { return .image(type) }
        return .ignore
    }
}
